#!/usr/bin/env bash
# Shared locations for the example scene, checkpoints, and local runtime files.
Q3DGSTREAM_ROOT="${Q3DGSTREAM_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
export Q3DGSTREAM_ROOT
export Q3DGSTREAM_DATA_DIR="${Q3DGSTREAM_DATA_DIR:-$Q3DGSTREAM_ROOT/data}"
export Q3DGSTREAM_SCENE_DIR="${Q3DGSTREAM_SCENE_DIR:-$Q3DGSTREAM_DATA_DIR/scenes/flame_steak}"
export Q3DGSTREAM_EXPERIMENT_DIR="${Q3DGSTREAM_EXPERIMENT_DIR:-$Q3DGSTREAM_DATA_DIR/experiments/int4_keep05}"
export Q3DGSTREAM_COMPRESSED_SCENE_DIR="${Q3DGSTREAM_COMPRESSED_SCENE_DIR:-$Q3DGSTREAM_EXPERIMENT_DIR/scenes/candidate}"
export Q3DGSTREAM_WIRE_DIR="${Q3DGSTREAM_WIRE_DIR:-$Q3DGSTREAM_EXPERIMENT_DIR/wire}"
export Q3DGSTREAM_PRIORITIES_DIR="${Q3DGSTREAM_PRIORITIES_DIR:-$Q3DGSTREAM_DATA_DIR/priorities}"
export Q3DGSTREAM_STAGES_DIR="${Q3DGSTREAM_STAGES_DIR:-$Q3DGSTREAM_PRIORITIES_DIR/stages}"
export Q3DGSTREAM_STATES_DIR="${Q3DGSTREAM_STATES_DIR:-$Q3DGSTREAM_DATA_DIR/states}"
export Q3DGSTREAM_SALIENCY_DIR="${Q3DGSTREAM_SALIENCY_DIR:-$Q3DGSTREAM_DATA_DIR/saliency/raw}"
export Q3DGSTREAM_TIMELINE_FILE="${Q3DGSTREAM_TIMELINE_FILE:-$Q3DGSTREAM_DATA_DIR/saliency/timeline.json}"
export Q3DGSTREAM_AUDIT_DIR="${Q3DGSTREAM_AUDIT_DIR:-$Q3DGSTREAM_DATA_DIR/audits}"
export Q3DGSTREAM_HASHGRID_DIR="${Q3DGSTREAM_HASHGRID_DIR:-$Q3DGSTREAM_DATA_DIR/hashgrid}"
export Q3DGSTREAM_CACHE_DIR="${Q3DGSTREAM_CACHE_DIR:-$Q3DGSTREAM_DATA_DIR/cache}"
export Q3DGSTREAM_LOG_DIR="${Q3DGSTREAM_LOG_DIR:-$Q3DGSTREAM_DATA_DIR/logs}"
export Q3DGSTREAM_TLS_CERT="${Q3DGSTREAM_TLS_CERT:-$Q3DGSTREAM_DATA_DIR/local/localhost.crt}"
export Q3DGSTREAM_TLS_KEY="${Q3DGSTREAM_TLS_KEY:-$Q3DGSTREAM_DATA_DIR/local/localhost.key}"
# Use an already active environment or the local .venv.
if [[ -z "${VIRTUAL_ENV:-}" ]]; then
  if [[ -f "$Q3DGSTREAM_ROOT/.venv/bin/activate" ]]; then
    source "$Q3DGSTREAM_ROOT/.venv/bin/activate"
  else
    echo "Activate a Python environment or create $Q3DGSTREAM_ROOT/.venv first." >&2
    return 1
  fi
fi
